"""
Data layer: load the versioned CSVs, clean them, and rebuild the analysis tables.

Versioned sources (``data/raw/``):
    papers.csv           one row per table entry of the reference study, including
                         the published (human) CLAIM domain scores
    llm_evaluations.csv  one row per (paper, LLM): CLAIM item ratings q1–q42

Derived tables (``data/processed/``, regenerated by this module):
    full_dataset.csv     papers ⨝ evaluations, long format: one row per
                         (paper, evaluator) with evaluator ∈ {Humans, ChatGPT,
                         Gemini, Claude}, item ratings and domain scores
    reduced_dataset.csv  same rows without item-level ratings
    scores.csv           analysis input, tidy format: one row per
                         (paper, evaluator, outcome) with the compliance
                         score as a whole-number percentage

Domain scores are not stored: they are computed from the item ratings
(``compute_domain_scores``), replicating the formulas of the original
spreadsheet: score = #Yes / (#Yes + #No) over the items of the domain;
"Not applicable" and missing ratings are excluded.

Usage (from the repository root):
    python -m src.data
"""

from __future__ import annotations

import logging
from pathlib import Path

import numpy as np
import pandas as pd

log = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

ROOT = Path(__file__).resolve().parents[1]
RAW_DIR = ROOT / "data" / "raw"
PROCESSED_DIR = ROOT / "data" / "processed"

PAPERS_PATH = RAW_DIR / "papers.csv"
LLM_EVALS_PATH = RAW_DIR / "llm_evaluations.csv"
FULL_PATH = PROCESSED_DIR / "full_dataset.csv"
REDUCED_PATH = PROCESSED_DIR / "reduced_dataset.csv"
SCORES_PATH = PROCESSED_DIR / "scores.csv"

ITEM_COLS = [f"q{i}" for i in range(1, 43)]
HUMAN_EVALUATOR = "Humans"
LLM_EVALUATORS = ["ChatGPT", "Gemini", "Claude"]
EVALUATOR_ORDER = [HUMAN_EVALUATOR, *LLM_EVALUATORS]

YES, NO, NA = "Yes", "No", "Not applicable"
# Raw spellings -> canonical rating (keys are lower-cased, whitespace removed).
RATING_MAP = {
    "yes": YES,
    "no": NO,
    "notapplicable": NA,
    "notapplicabble": NA,  # typo in the source spreadsheet
    "na": NA,
}

PAPER_META_COLS = [
    "paper_id", "author", "year", "journal", "country", "images",
    "segmentation", "cases", "dataset", "validation",
    "performance_evaluation", "public_code",
]
PAPER_REF_COLS = ["paper", "link", "link_type", "note"]

# Mapping of CLAIM items to the four domains of the reference study
# (taken from the formulas of the original spreadsheet).
DOMAINS: dict[str, list[int]] = {
    "study_description_domain": [*range(1, 7), *range(40, 43)],     # Q1–6, Q40–42
    "dataset_description_domain": [*range(7, 22), 33, 34],          # Q7–21, Q33–34
    "model_description_domain": [*range(22, 28)],                   # Q22–27
    "performance_domain": [*range(28, 33), *range(35, 40)],         # Q28–32, Q35–39
}
OVERALL_SCORE = "all_domains"
SCORE_COLS = [*DOMAINS, OVERALL_SCORE]

# paper_id 35 appears twice in papers.csv (two table rows, same reference:
# "Curiale" / "Curialea"). The LLMs assessed the article once, so one human
# entry must be chosen for the comparison. "Curiale" reproduces the original
# Full_Dataset sheet.
HUMAN_ENTRY_FOR_DUPLICATES = {35: "Curiale"}

# Domain scores taken as recorded in the original database instead of the
# item-level value: (paper_id, evaluator, score column) -> score (0–1).
SPREADSHEET_OVERRIDES = {
    # value recorded in the original database
    (57, "Gemini", "model_description_domain"): 0.0,
    # all items "Not applicable" (#DIV/0! in the spreadsheet), recorded as 0
    (56, "Claude", "model_description_domain"): 0.0,
}

# ---------------------------------------------------------------------------
# Loading and cleaning
# ---------------------------------------------------------------------------


def load_papers(path: str | Path = PAPERS_PATH) -> pd.DataFrame:
    """Paper metadata and human (published) CLAIM scores."""
    df = pd.read_csv(path)
    df["cases"] = pd.to_numeric(df["cases"].replace("NR", np.nan))  # NR = not reported
    return df


def normalize_rating(value) -> str | float:
    """Map a raw rating to Yes / No / Not applicable; NaN stays NaN."""
    if pd.isna(value):
        return np.nan
    key = "".join(str(value).split()).lower()
    if key not in RATING_MAP:
        raise ValueError(f"Unknown rating: {value!r}")
    return RATING_MAP[key]


def load_llm_evaluations(path: str | Path = LLM_EVALS_PATH) -> pd.DataFrame:
    """LLM item ratings with canonical rating labels."""
    df = pd.read_csv(path, parse_dates=["evaluation_date"])
    df[ITEM_COLS] = df[ITEM_COLS].map(normalize_rating)
    return df


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------


def validate(papers: pd.DataFrame, evals: pd.DataFrame) -> None:
    """Integrity checks; raise on structural errors, warn on data gaps."""
    dup_keys = papers.duplicated(["paper_id", "author"])
    assert not dup_keys.any(), "(paper_id, author) must be unique in papers.csv"

    dup_ids = papers.loc[papers["paper_id"].duplicated(keep=False), "paper_id"].unique()
    unresolved = set(dup_ids) & set(evals["paper_id"]) - set(HUMAN_ENTRY_FOR_DUPLICATES)
    assert not unresolved, f"Duplicated paper_id without resolution rule: {unresolved}"

    assert not evals.duplicated(["paper_id", "evaluator"]).any(), \
        "(paper_id, evaluator) must be unique in llm_evaluations.csv"
    assert set(evals["evaluator"]) <= set(LLM_EVALUATORS), "Unknown evaluator"

    orphans = set(evals["paper_id"]) - set(papers["paper_id"])
    assert not orphans, f"Evaluations without paper metadata: {orphans}"

    counts = evals.groupby("paper_id")["evaluator"].nunique()
    incomplete = counts[counts < len(LLM_EVALUATORS)].index.tolist()
    if incomplete:
        log.warning("Papers not assessed by every LLM: %s", incomplete)

    missing = evals[ITEM_COLS].isna()
    for idx in missing.index[missing.any(axis=1)]:
        row = evals.loc[idx]
        items = missing.columns[missing.loc[idx]].tolist()
        log.warning("Missing rating: paper %s, %s, items %s",
                    row["paper_id"], row["evaluator"], items)


# ---------------------------------------------------------------------------
# Scores
# ---------------------------------------------------------------------------


def _yes_fraction(ratings: pd.DataFrame) -> pd.Series:
    yes = (ratings == YES).sum(axis=1)
    no = (ratings == NO).sum(axis=1)
    denom = yes + no
    return (yes / denom).where(denom > 0)  # NaN if every item is NA/missing


def compute_domain_scores(evals: pd.DataFrame) -> pd.DataFrame:
    """Per-row domain and overall scores from item ratings."""
    scores = pd.DataFrame(index=evals.index)
    for domain, items in DOMAINS.items():
        scores[domain] = _yes_fraction(evals[[f"q{i}" for i in items]])
    scores[OVERALL_SCORE] = _yes_fraction(evals[ITEM_COLS])
    return scores


# ---------------------------------------------------------------------------
# Joins
# ---------------------------------------------------------------------------


def human_entries(papers: pd.DataFrame, paper_ids) -> pd.DataFrame:
    """One human row per evaluated paper (resolving duplicated paper_id)."""
    sub = papers[papers["paper_id"].isin(paper_ids)]
    keep = pd.Series(True, index=sub.index)
    for pid, author in HUMAN_ENTRY_FOR_DUPLICATES.items():
        keep &= ~((sub["paper_id"] == pid) & (sub["author"] != author))
    sub = sub[keep]
    assert sub["paper_id"].is_unique
    return sub


def build_full_dataset(papers: pd.DataFrame, evals: pd.DataFrame) -> pd.DataFrame:
    """papers ⨝ evaluations in long format (Humans + LLMs), with scores."""
    paper_ids = evals["paper_id"].unique()
    humans = human_entries(papers, paper_ids)
    meta = humans[PAPER_META_COLS + PAPER_REF_COLS]

    llm = evals.join(compute_domain_scores(evals))
    llm = llm.merge(meta, on="paper_id", how="left", validate="many_to_one")

    hum = humans[PAPER_META_COLS + PAPER_REF_COLS + SCORE_COLS].assign(
        evaluator=HUMAN_EVALUATOR, evaluation_date=pd.NaT
    )

    full = pd.concat([hum, llm], ignore_index=True)
    order = {pid: i for i, pid in enumerate(paper_ids)}  # keep source order
    full = full.assign(
        _p=full["paper_id"].map(order),
        _e=full["evaluator"].map({e: i for i, e in enumerate(EVALUATOR_ORDER)}),
    ).sort_values(["_p", "_e"]).drop(columns=["_p", "_e"])

    cols = (PAPER_META_COLS + ["evaluator", "evaluation_date"] + ITEM_COLS
            + SCORE_COLS + PAPER_REF_COLS + ["annotation"])
    return full[cols].reset_index(drop=True)


def build_reduced_dataset(full: pd.DataFrame) -> pd.DataFrame:
    """Full dataset without item-level ratings."""
    return full.drop(columns=ITEM_COLS)


def to_percent(x: pd.Series | pd.DataFrame):
    """Fraction -> whole-number percentage, rounding half up (as Excel ROUND).

    The intermediate ``round(..., 6)`` removes floating-point noise
    (e.g. 0.58 * 100 = 57.999...) before rounding.
    """
    return np.floor(np.round(x * 100, 6) + 0.5)


def apply_spreadsheet_overrides(full: pd.DataFrame) -> pd.DataFrame:
    """Replace the scores listed in ``SPREADSHEET_OVERRIDES``."""
    full = full.copy()
    for (pid, evaluator, col), value in SPREADSHEET_OVERRIDES.items():
        mask = (full["paper_id"] == pid) & (full["evaluator"] == evaluator)
        assert mask.sum() == 1, (pid, evaluator, col)
        full.loc[mask, col] = value
    return full


def prepare_scores(full: pd.DataFrame) -> pd.DataFrame:
    """Analysis input in tidy format: paper_id, evaluator, outcome, score.

    Scores are whole-number percentages (as in the original spreadsheet) with
    ``SPREADSHEET_OVERRIDES`` applied.
    """
    full = apply_spreadsheet_overrides(full)
    scores = full.melt(
        id_vars=["paper_id", "evaluator"], value_vars=SCORE_COLS,
        var_name="outcome", value_name="score",
    )
    scores["score"] = to_percent(scores["score"])
    return scores


def load_full_dataset() -> pd.DataFrame:
    """Convenience entry point for analysis scripts."""
    papers, evals = load_papers(), load_llm_evaluations()
    validate(papers, evals)
    return build_full_dataset(papers, evals)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def write_processed() -> tuple[pd.DataFrame, pd.DataFrame]:
    """Build and save the processed tables; return (full dataset, scores)."""
    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    full = load_full_dataset()
    scores = prepare_scores(full)
    full.to_csv(FULL_PATH, index=False)
    build_reduced_dataset(full).to_csv(REDUCED_PATH, index=False)
    scores.to_csv(SCORES_PATH, index=False)
    log.info("full_dataset: %d rows x %d cols -> %s", *full.shape, PROCESSED_DIR)
    return full, scores


def main() -> None:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s | %(message)s")
    write_processed()


if __name__ == "__main__":
    main()
